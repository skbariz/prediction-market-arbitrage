"""
Runs one scan of Kalshi + Polymarket and writes LIVE_OPPORTUNITIES.md.
Called by GitHub Actions on a schedule; can also be run locally:

    python scripts/update_live_table.py
"""
import sys
import asyncio
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.clients.kalshi import KalshiClient
from src.clients.polymarket import PolymarketClient
from src.core.matcher import match_markets
from src.core.detector import detect_opportunities


def _days_left(dt):
    if dt is None:
        return "?"
    d = (dt - datetime.now(timezone.utc)).days
    return str(max(d, 0))


async def scan():
    async with KalshiClient() as kalshi, PolymarketClient() as poly:
        k_markets, p_markets = await asyncio.gather(
            kalshi.get_markets(),
            poly.get_markets(),
        )
    return k_markets, p_markets


def build_markdown(k_markets, p_markets, timestamp: str) -> str:
    pairs = match_markets(k_markets, p_markets)
    opportunities = detect_opportunities(pairs)

    lines = [
        "# Live Arbitrage Opportunities",
        "",
        f"**Last updated:** {timestamp} UTC &nbsp;·&nbsp; "
        f"Kalshi: {len(k_markets)} markets &nbsp;·&nbsp; "
        f"Polymarket: {len(p_markets)} markets &nbsp;·&nbsp; "
        f"Matched pairs: {len(pairs)}",
        "",
        "> This file is auto-updated every 15 minutes by GitHub Actions.",
        "> Prices shown are **ask prices** (what you pay to enter).",
        "> An opportunity exists when combined cost + fees < $1.00.",
        "",
    ]

    if opportunities:
        lines += [
            f"## 🟢 {len(opportunities)} Opportunity Found",
            "",
            "| Market | Resolves | Kalshi Leg | Poly Leg | Gross Cost | Est. Fees | Net Profit |",
            "|--------|----------|-----------|---------|-----------|----------|-----------|",
        ]
        for opp in opportunities:
            market = opp.kalshi_market.title[:55]
            days = _days_left(opp.kalshi_market.close_time)
            k_leg = f"{opp.kalshi_side} @ {opp.kalshi_entry:.3f}"
            p_leg = f"{opp.poly_side} @ {opp.poly_entry:.3f}"
            gross = f"{opp.gross_cost:.3f}"
            fees = f"${opp.fees:.4f}"
            profit = f"**{opp.net_profit_pct*100:.2f}%** (${opp.net_profit_usd:.2f})"
            lines.append(f"| {market} | {days}d | {k_leg} | {p_leg} | {gross} | {fees} | {profit} |")
        lines += [
            "",
            "> **How to execute:** Buy the Kalshi leg on [kalshi.com](https://kalshi.com) "
            "and the Polymarket leg on [polymarket.com](https://polymarket.com) simultaneously. "
            "See [README.md](README.md) for a full execution guide.",
            "",
        ]
    else:
        lines += [
            "## ⚪ No Opportunities Right Now",
            "",
            "Markets are efficiently priced. "
            "Gaps typically open during live game events or breaking news "
            "when one platform updates prices faster than the other.",
            "",
        ]

    lines += [
        "## All Matched Pairs",
        "",
        "These are the markets the bot has confirmed exist on both platforms. "
        "A gap needs to reach roughly **9–10¢** to clear fees and the 2% minimum profit threshold.",
        "",
        "| Market | Score | Kalshi Yes | Poly Yes | Gap | Closes |",
        "|--------|-------|-----------|---------|-----|--------|",
    ]
    for km, pm, score in pairs:
        gap_cents = abs(km.price.yes - pm.price.yes) * 100
        closes = km.close_time.strftime("%Y-%m-%d") if km.close_time else "?"
        lines.append(
            f"| {km.title[:55]} | {score:.0f} | "
            f"{km.price.yes:.3f} | {pm.price.yes:.3f} | "
            f"{gap_cents:.1f}¢ | {closes} |"
        )

    lines += [
        "",
        "---",
        "",
        "*Generated by [prediction-market-arbitrage](https://github.com/skbariz/prediction-market-arbitrage)*",
    ]

    return "\n".join(lines) + "\n"


async def main():
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M")
    print(f"Scanning markets at {timestamp} UTC...")

    k_markets, p_markets = await scan()
    print(f"  Kalshi: {len(k_markets)} | Polymarket: {len(p_markets)}")

    md = build_markdown(k_markets, p_markets, timestamp)

    out = Path(__file__).parent.parent / "LIVE_OPPORTUNITIES.md"
    out.write_text(md, encoding="utf-8")
    print(f"  Written to {out}")


if __name__ == "__main__":
    asyncio.run(main())
