"""Renders scan results as a Markdown report (used for the published live-opportunities page)."""

from __future__ import annotations

import re
from datetime import datetime, timezone

from prediction_arb.config import Settings
from prediction_arb.scanner import ScanResult

_MD_SPECIAL = re.compile(r"([\\`*_{}\[\]()#+!|~>-])")
_AUTOLINK = re.compile(r"://|(?i:\bwww)\.|@")


def escape_md(text: str, max_len: int = 70) -> str:
    """Make untrusted text (market titles from third-party APIs) safe inside a Markdown table cell."""
    text = " ".join(text.split())
    if len(text) > max_len:
        text = text[: max_len - 1].rstrip() + "…"
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    # GitHub turns bare URLs, "www." hosts, and @handles into links/mentions even when the
    # Markdown link syntax is escaped; a zero-width space breaks those patterns.
    text = _AUTOLINK.sub(lambda m: m.group(0)[0] + "\u200b" + m.group(0)[1:], text)
    return _MD_SPECIAL.sub(r"\\\1", text)


def render_markdown(result: ScanResult, settings: Settings, now: datetime | None = None) -> str:
    now = now or datetime.now(timezone.utc)
    lines = [
        "# Live Arbitrage Opportunities",
        "",
        f"**Last updated:** {now:%Y-%m-%d %H:%M} UTC · "
        f"Kalshi: {len(result.kalshi_markets)} markets · "
        f"Polymarket: {len(result.poly_markets)} markets · "
        f"Matched pairs: {len(result.pairs)}",
        "",
        "> Prices are best **ask** prices (what you pay to buy). Profit is after estimated taker "
        f"fees on a ${settings.max_position_usd:,.0f} position, with a "
        f"{settings.min_profit_pct:.0%} minimum. Quotes go stale within seconds — this page is "
        "informational only and is **not financial advice**.",
        "",
    ]

    if result.opportunities:
        lines += [
            f"## {len(result.opportunities)} opportunit{'y' if len(result.opportunities) == 1 else 'ies'}",
            "",
            "| Market | Closes | Kalshi leg | Polymarket leg | Contracts | Cost | Fees | Net profit |",
            "|---|---|---|---|---:|---:|---:|---:|",
        ]
        for opp in result.opportunities:
            closes = (
                f"{opp.kalshi_market.resolves_at:%Y-%m-%d}"
                if opp.kalshi_market.resolves_at
                else "?"
            )
            lines.append(
                f"| {escape_md(opp.kalshi_market.title)} | {closes} "
                f"| {opp.kalshi_side.value.upper()} @ {opp.kalshi_price:.3f} "
                f"| {opp.poly_side.value.upper()} @ {opp.poly_price:.3f} "
                f"| {opp.contracts} | ${opp.total_cost:,.2f} | ${opp.total_fees:,.2f} "
                f"| **{opp.net_profit_pct:.2%}** (${opp.net_profit_usd:,.2f}) |"
            )
    else:
        lines += [
            "## No opportunities right now",
            "",
            "Markets are efficiently priced. Gaps typically open briefly during live events or "
            "breaking news, when one platform reprices faster than the other.",
        ]

    lines += [
        "",
        "## Matched pairs",
        "",
        "Markets the matcher believes describe the same event on both platforms.",
        "",
        "| Market (Kalshi title) | Score | Kalshi YES ask | Polymarket YES ask | Gap | Closes |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for pair in result.pairs:
        k, p = pair.kalshi, pair.polymarket
        closes = f"{k.resolves_at:%Y-%m-%d}" if k.resolves_at else "?"
        gap_cents = abs(k.price.yes - p.price.yes) * 100
        lines.append(
            f"| {escape_md(k.title)} | {pair.score:.0f} | {k.price.yes:.3f} | {p.price.yes:.3f} "
            f"| {gap_cents:.1f}¢ | {closes} |"
        )
    if not result.pairs:
        lines.append("| *none* | | | | | |")

    lines += [
        "",
        "---",
        "",
        "*Generated by [prediction-market-arbitrage]"
        "(https://github.com/skbariz/prediction-market-arbitrage).*",
        "",
    ]
    return "\n".join(lines)
